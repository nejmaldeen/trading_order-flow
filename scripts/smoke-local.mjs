import assert from 'node:assert/strict';
const base=process.env.REPLAY_TEST_URL || 'http://127.0.0.1:5173';
if(!['127.0.0.1','localhost'].includes(new URL(base).hostname))throw new Error('Local test only');
const owner=`replay-test-${crypto.randomUUID()}`;
const headers={'content-type':'application/json','oai-authenticated-user-id':owner};
let state=(await fetch(base+'/api/lab',{headers}).then(r=>r.json())).state;let checks=0;
async function post(body,status=200){const r=await fetch(base+'/api/lab',{method:'POST',headers,body:JSON.stringify({...body,revision:state.revision}),signal:AbortSignal.timeout(90000)});const p=await r.json();assert.equal(r.status,status,JSON.stringify(p));if(p.state)state=p.state;checks++;return p;}
const started=await post({action:'start',symbol:'BTCUSDT',startTime:Date.UTC(2025,0,1,9),timeframe:'15m',confirmReplace:true});
const session=()=>state.sessions.find(s=>s.id===state.activeSessionId);
assert.ok(started.candles.every(c=>c.closeTime<=session().cursorTime));
const first=session().cursorTime;
await post({action:'step',count:1});assert.equal(session().cursorTime,first+60000);
const p=await post({action:'step',count:64});assert.equal(p.candles.length,64);assert.equal(session().cursorTime,first+65*60000);
const last=p.candles.at(-1).close;
await post({action:'buy',orderType:'limit',orderPrice:last*.9,notional:100,stopLoss:last*.8,takeProfit:last*1.2});
await post({action:'step',count:1});assert.equal(state.trades[0].status,'pending');
await post({action:'cancel'});assert.equal(state.trades[0].status,'cancelled');
await post({action:'buy',orderType:'stop',orderPrice:last*1.05,notional:100,stopLoss:last*.9,takeProfit:last*1.2});
assert.equal(state.trades[0].orderType,'stop');await post({action:'cancel'});
await post({action:'buy',notional:1000,stopLoss:last*.8,takeProfit:last*1.2},400);
await post({action:'buy',notional:100,stopLoss:last*.8,takeProfit:last*1.2});
await post({action:'step',count:1});assert.equal(state.trades[0].status,'open');
const risk=state.trades[0].initialRisk;
await post({action:'risk',tradeId:state.trades[0].id,stopLoss:state.trades[0].entryPrice*1.001,takeProfit:last*1.2});assert.equal(state.trades[0].initialRisk,risk);
await post({action:'risk',tradeId:state.trades[0].id,stopLoss:last*2,takeProfit:last*1.2},400);
await post({action:'close'});await post({action:'step',count:1});assert.equal(state.trades[0].status,'closed');
const before=session().cursorTime,revision=state.revision;
const results=await Promise.all([1,2].map(()=>fetch(base+'/api/lab',{method:'POST',headers,body:JSON.stringify({action:'step',count:1,revision})}).then(async r=>({status:r.status,p:await r.json()}))));
assert.deepEqual(results.map(r=>r.status).sort(),[200,409]);state=results.find(r=>r.status===200).p.state;assert.equal(session().cursorTime,before+60000);checks++;
const restored=await fetch(base+'/api/lab?timeframe=1d',{headers}).then(r=>r.json());assert.ok(restored.candles.every(c=>c.closeTime<=session().cursorTime));assert.deepEqual(restored.state,state);checks++;
await post({action:'start',symbol:'BTCUSDT',startTime:Date.UTC(2025,0,2)},409);
console.log(JSON.stringify({checks,owner,source:restored.source,finalCursor:session().cursorTime,trades:state.trades.length,concurrency:results.map(r=>r.status)}));
